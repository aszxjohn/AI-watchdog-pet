import { sourceCodeSchema, type SourceCode } from './sources';
import { z } from './zod-setup';

/**
 * The detection event contract (AD-5, AD-21). Every adapter emits only these
 * events; main/detection's reducer alone turns them into the 8 states.
 */

/**
 * Where an event's fact came from: an AI tool's log, a registry (Claude
 * Code's status file), or main/detection/inference.
 */
export const VIA_CODES = ['log', 'registry', 'inferred'] as const;

export const viaSchema = z.enum(VIA_CODES);

export type Via = z.infer<typeof viaSchema>;

export const CONFIDENCE_CODES = ['exact', 'inferred'] as const;

export const confidenceSchema = z.enum(CONFIDENCE_CODES);

export type Confidence = z.infer<typeof confidenceSchema>;

/** Only an inferred fact is `inferred`; `log` and `registry` are `exact`. */
export function confidenceFor(via: Via): Confidence {
  return via === 'inferred' ? 'inferred' : 'exact';
}

/**
 * Longest native id, tool call id, request id, tool name or display name, in
 * UTF-16 code units.
 */
export const DETECTION_ID_MAX_LENGTH = 256;

/** C0 controls, DEL and C1 controls (Unicode general category Cc). */
const CONTROL_CHARACTER = /\p{Cc}/u;

function hasNoControlCharacter(value: string): boolean {
  return !CONTROL_CHARACTER.test(value);
}

/**
 * A source's native id (see sources.ts for which id each source uses): 1 to
 * DETECTION_ID_MAX_LENGTH characters, no control characters. It may contain
 * `:`; a session key splits at its first `:`.
 */
export const nativeIdSchema = z
  .string()
  .min(1)
  .max(DETECTION_ID_MAX_LENGTH)
  .refine(hasNoControlCharacter, {
    message: 'a native id has no control characters',
  });

/**
 * `<source>:<native id>`, the one key a session has across adapters, the
 * reducer, the pool and StageView.
 */
export const sessionKeySchema = z
  .templateLiteral([
    sourceCodeSchema,
    ':',
    z.string().min(1).max(DETECTION_ID_MAX_LENGTH),
  ])
  .refine(hasNoControlCharacter, {
    message: 'a native id has no control characters',
  });

export type SessionKey = z.infer<typeof sessionKeySchema>;

/**
 * The session key for a source's native id, or null when the id is not a
 * valid native id (adapters skip such records instead of throwing).
 */
export function makeSessionKey(
  source: SourceCode,
  nativeId: string,
): SessionKey | null {
  if (!nativeIdSchema.safeParse(nativeId).success) {
    return null;
  }
  return `${source}:${nativeId}`;
}

/** A tool call id, request id, tool name or display name. */
const detectionIdSchema = z.string().min(1).max(DETECTION_ID_MAX_LENGTH);

/**
 * When the AI tool wrote the fact, epoch milliseconds. It is only for
 * ordering and display; every duration the reducer measures uses the
 * monotonic clock at receipt (AD-22).
 */
export const eventTsSchema = z.int().nonnegative();

/**
 * Fields every event carries. `sessionKey` must start with `<source>:` and
 * `confidence` must equal `confidenceFor(via)`; detectionEventSchema checks
 * both.
 */
const commonFields = {
  source: sourceCodeSchema,
  sessionKey: sessionKeySchema,
  ts: eventTsSchema,
  via: viaSchema,
  confidence: confidenceSchema,
};

/**
 * Tool call id: from the tool, or generated by the adapter so that a call's
 * start and end match.
 */
const toolCallIdField = { toolCallId: detectionIdSchema };

/**
 * Request id: equals the tool call id when a tool call raised the request.
 */
const requestIdField = { requestId: detectionIdSchema };

export const sessionStartEventSchema = z.strictObject({
  type: z.literal('session.start'),
  ...commonFields,
});

export const sessionEndEventSchema = z.strictObject({
  type: z.literal('session.end'),
  ...commonFields,
});

/** Metadata only: it opens and closes no condition. */
export const sessionMetaEventSchema = z.strictObject({
  type: z.literal('session.meta'),
  ...commonFields,
  displayName: detectionIdSchema,
});

export const turnStartEventSchema = z.strictObject({
  type: z.literal('turn.start'),
  ...commonFields,
});

export const turnEndEventSchema = z.strictObject({
  type: z.literal('turn.end'),
  ...commonFields,
});

export const toolStartEventSchema = z.strictObject({
  type: z.literal('tool.start'),
  ...commonFields,
  ...toolCallIdField,
  toolName: detectionIdSchema,
});

export const toolEndEventSchema = z.strictObject({
  type: z.literal('tool.end'),
  ...commonFields,
  ...toolCallIdField,
});

export const approvalRequestEventSchema = z.strictObject({
  type: z.literal('approval.request'),
  ...commonFields,
  ...requestIdField,
});

export const approvalResolvedEventSchema = z.strictObject({
  type: z.literal('approval.resolved'),
  ...commonFields,
  ...requestIdField,
});

export const questionRequestEventSchema = z.strictObject({
  type: z.literal('question.request'),
  ...commonFields,
  ...requestIdField,
});

export const questionResolvedEventSchema = z.strictObject({
  type: z.literal('question.resolved'),
  ...commonFields,
  ...requestIdField,
});

export const errorEventSchema = z.strictObject({
  type: z.literal('error'),
  ...commonFields,
});

/** A heartbeat: it only moves the session's last-event time. */
export const activityEventSchema = z.strictObject({
  type: z.literal('activity'),
  ...commonFields,
});

/** The event types, in AD-21's listing order. */
export const DETECTION_EVENT_TYPES = [
  'session.start',
  'session.end',
  'session.meta',
  'turn.start',
  'turn.end',
  'tool.start',
  'tool.end',
  'approval.request',
  'approval.resolved',
  'question.request',
  'question.resolved',
  'error',
  'activity',
] as const;

export type DetectionEventType = (typeof DETECTION_EVENT_TYPES)[number];

/** Any detection event, told apart by `type`. */
export const detectionEventSchema = z
  .discriminatedUnion('type', [
    sessionStartEventSchema,
    sessionEndEventSchema,
    sessionMetaEventSchema,
    turnStartEventSchema,
    turnEndEventSchema,
    toolStartEventSchema,
    toolEndEventSchema,
    approvalRequestEventSchema,
    approvalResolvedEventSchema,
    questionRequestEventSchema,
    questionResolvedEventSchema,
    errorEventSchema,
    activityEventSchema,
  ])
  .refine((event) => event.sessionKey.startsWith(`${event.source}:`), {
    message: 'sessionKey starts with the event source',
    path: ['sessionKey'],
  })
  .refine((event) => event.confidence === confidenceFor(event.via), {
    message: 'confidence follows from via',
    path: ['confidence'],
  });

export type DetectionEvent = z.infer<typeof detectionEventSchema>;

/** The event of one type. */
export type DetectionEventOf<T extends DetectionEventType> = Extract<
  DetectionEvent,
  { type: T }
>;
